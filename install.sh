#!/usr/bin/env bash
# Installer for the Session Search MCP server.
#
# For Windows, prefer the README's PowerShell steps or `make install`; this
# script is for macOS and Linux, and needs bash.

set -euo pipefail

echo "Session Search MCP - Installer"
echo "============================="

NC='\033[0m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'

log_info() { echo -e "${GREEN}[INFO]${NC} $1"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }

MODEL_DIR="${MODEL_DIR:-$HOME/models}"
INDEX_DIR="${INDEX_DIR:-$HOME/.opencode}"

# Two distinct models, for two distinct jobs.
#
# The embedding model MUST be a sentence-embedding model. A generative chat
# model emits one vector per token rather than one pooled vector, so it cannot
# be used here - see docs/adr/005.
EMBED_MODEL="bge-small-en-v1.5-q8_0.gguf"
EMBED_URL="https://huggingface.co/ggml-org/bge-small-en-v1.5-Q8_0-GGUF/resolve/main/${EMBED_MODEL}"

# The chat model is optional. Without it, search returns ranked matches rather
# than a written answer.
CHAT_MODEL="Qwen3.5-4B-Q4_K_M.gguf"
CHAT_URL="https://huggingface.co/unsloth/Qwen3.5-4B-GGUF/resolve/main/${CHAT_MODEL}"

download() {
    local url="$1" dest="$2" label="$3"

    if [ -f "$dest" ]; then
        log_info "${label} already present: $dest"
        return
    fi

    log_info "Downloading ${label} to ${dest} ..."
    if command -v curl >/dev/null 2>&1; then
        curl -L --fail --progress-bar -o "$dest" "$url"
    elif command -v wget >/dev/null 2>&1; then
        wget --show-progress -O "$dest" "$url"
    else
        log_error "Need curl or wget to download models."
        exit 1
    fi

    [ -f "$dest" ] || { log_error "Download failed: $label"; exit 1; }
}

check_python() {
    if ! command -v python3 >/dev/null 2>&1; then
        log_error "Python 3 is required but was not found."
        exit 1
    fi

    version=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
    major=${version%%.*}
    minor=${version##*.}

    if [ "$major" -lt 3 ] || { [ "$major" -eq 3 ] && [ "$minor" -lt 11 ]; }; then
        log_error "Python 3.11+ required (found ${version})."
        exit 1
    fi
    log_info "Python ${version} OK"
}

install_deps() {
    log_info "Installing Python dependencies ..."
    # CPU-only by default. GPU builds need CUDA toolchain support, and the
    # prebuilt Windows CUDA wheels stop well before current llama.cpp versions.
    python3 -m pip install -e ".[dev]"
    log_info "Dependencies installed"
}

write_env() {
    local env_file=".env"
    if [ -f "$env_file" ]; then
        log_info ".env already exists; leaving it alone"
        return
    fi

    cat > "$env_file" <<EOF
# Session Search MCP - generated by install.sh

# Storage
SESSION_SEARCH_DATABASE_PATH=${INDEX_DIR}/session_search.db
SESSION_SEARCH_OPENCODE_DB_PATH=${HOME}/.local/share/opencode/opencode.db

# Embedding model: fixed 384-dim pooled vectors, 512-token window
SESSION_SEARCH_MODEL_PATH=${MODEL_DIR}/${EMBED_MODEL}
SESSION_SEARCH_MODEL_N_CTX=512
SESSION_SEARCH_MODEL_N_GPU_LAYERS=0
SESSION_SEARCH_EMBEDDING_DIM=384

# Answer synthesis (optional - comment out to return ranked matches only)
SESSION_SEARCH_CHAT_MODEL_PATH=${MODEL_DIR}/${CHAT_MODEL}
SESSION_SEARCH_MAX_SUMMARY_TOKENS=150

# Search. 0.55 is calibrated: real matches score 0.60-0.85, unrelated
# questions top out near 0.535. See docs/adr/005.
SESSION_SEARCH_SIMILARITY_THRESHOLD=0.55
SESSION_SEARCH_DEFAULT_TOP_K=5

SESSION_SEARCH_SERVER_NAME=session-search
SESSION_SEARCH_LOG_LEVEL=INFO
EOF
    log_info "Wrote ${env_file}"
}

verify() {
    log_info "Verifying ..."
    python3 -c "import session_search; from session_search.infrastructure.config import settings; print('config OK')" \
        || log_warn "Import failed - try: pip install -e ."

    if [ -f "${MODEL_DIR}/${EMBED_MODEL}" ]; then
        log_info "Embedding model present"
    else
        log_warn "Embedding model missing - search will fail until it is downloaded"
    fi
}

main() {
    check_python
    mkdir -p "$MODEL_DIR" "$INDEX_DIR"
    download "$EMBED_URL" "${MODEL_DIR}/${EMBED_MODEL}" "embedding model (~36 MB)"

    if [ "${WITH_CHAT_MODEL:-0}" = "1" ]; then
        log_info "Chat model is ~2.7 GB. Downloading ..."
        download "$CHAT_URL" "${MODEL_DIR}/${CHAT_MODEL}" "chat model"
    else
        log_info "Skipping the optional chat model."
        log_info "  Set WITH_CHAT_MODEL=1 to include it, or add it later."
        log_info "  Without it, search returns ranked matches instead of prose."
    fi

    install_deps
    write_env
    verify

    echo ""
    echo "Done. Next:"
    echo "  1. Register the server in your MCP client config (see README.md)"
    echo "  2. python -m session_search health"
    echo "  3. python -m session_search search \"what did we decide about X\""
    echo ""
}

main "$@"